# Unicode symbols that the T1-encoded Times font cannot print; pandoc leaves
# them as is, so they are rewritten as inline math before conversion.
SUPERSCRIPTS = str.maketrans("⁰¹²³⁴⁵⁶⁷⁸⁹⁻⁺", "0123456789-+")
SYMBOLS = {
    "×": r"\times",
    "≤": r"\leq",
    "≥": r"\geq",
    "±": r"\pm",
    "−": r"-",
    "≈": r"\approx",
    "≠": r"\neq",
    "→": r"\rightarrow",
    "·": r"\cdot",
    "†": r"^{\dagger}",
}


def raw_math(body: str) -> str:
    """Inline math as a pandoc raw LaTeX inline, so it survives whatever follows it
    (pandoc does not treat $...$ as math when a digit follows the closing $)."""
    return "`$" + body + "$`{=latex}"


# --------------------------------------------------------------------------- #
# Markdown reading
# --------------------------------------------------------------------------- #
def split_front_matter(text: str) -> tuple[dict, str]:
    """Return (front matter dict, body) for a file that may start with ---."""
    if not text.startswith("---"):
        return {}, text
    m = re.match(r"^---[ \t]*\n(.*?)\n---[ \t]*\n", text, re.S)
    if not m:
        return {}, text
    raw, body = m.group(1), text[m.end():]
    meta: dict = {}
    if yaml is not None:
        try:
            loaded = yaml.safe_load(raw)
            if isinstance(loaded, dict):
                meta = loaded
        except yaml.YAMLError:
            meta = {}
    if not meta:  # minimal fallback: top-level "key: value" lines
        for line in raw.splitlines():
            mm = re.match(r"^([A-Za-z_][\w-]*):\s*(.*)$", line)
            if mm:
                meta[mm.group(1)] = mm.group(2).strip().strip('"').strip("'")
    return meta, body


def split_h1(body: str) -> tuple[str | None, str]:
    """Pop the first Markdown H1 (if it is the first non-blank line)."""
    lines = body.lstrip("\n").split("\n")
    if lines and re.match(r"^#\s+", lines[0]):
        title = re.sub(r"^#\s+", "", lines[0]).strip()
        title = re.sub(r"^\d+(\.\d+)*\.?\s+", "", title)
        return title, "\n".join(lines[1:])
    return None, body


