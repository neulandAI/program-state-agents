MD_CONSTRUCTS = {
    "footnote": re.compile(r"\[\^[^\]]+\]"),
    "html tag": re.compile(r"<(?!https?://)[A-Za-z/!][^>]*>"),
    "display math $$": re.compile(r"\$\$"),
    "strikethrough": re.compile(r"~~[^~]+~~"),
    "task list": re.compile(r"^\s*[-*]\s+\[[ xX]\]", re.M),
    "definition list": re.compile(r"^:\s+", re.M),
    "fenced code block": re.compile(r"^```", re.M),
    "heading level 4+": re.compile(r"^#{4,}\s", re.M),
    "inline image (not alone on its line)": re.compile(
        r"^(?!\s*!\[[^\]]*\]\([^)]*\)(\{[^}]*\})?\s*$).*!\[", re.M),
}
TEX_LEFTOVERS = {
    "longtable (table not converted)": re.compile(r"\\begin\{longtable\}"),
    "pandocbounded (inline image)": re.compile(r"\\pandocbounded"),
    "strikeout \\st (needs soul)": re.compile(r"\\st\{"),
    "natbib command left": re.compile(r"\\cite(p|t|alp)\b"),
    "verbatim block": re.compile(r"\\begin\{verbatim\}"),
}


def scan_markdown(name: str, md: str, findings: list[str]) -> None:
    for label, rx in MD_CONSTRUCTS.items():
        n = len(rx.findall(md))
        if n:
            findings.append(f"{name}: {label} x{n}")


def scan_tex(name: str, tex: str, findings: list[str]) -> None:
    for label, rx in TEX_LEFTOVERS.items():
        n = len(rx.findall(tex))
        if n:
            findings.append(f"{name}: {label} x{n}")
    non_ascii = sorted({c for c in tex if ord(c) > 127})
    if non_ascii:
        findings.append(f"{name}: non-ASCII characters left in LaTeX: {' '.join(non_ascii)}")


def parse_log(log: str, blg: str) -> dict:
    out: dict = {}
    undef = set(re.findall(r"Citation `([^']+)' on page \d+ undefined", log))
    undef |= set(re.findall(r'I didn\'t find a database entry for "([^"]+)"', blg))
    out["undefined_citations"] = sorted(undef)
    out["undefined_refs"] = sorted(set(re.findall(r"Reference `([^']+)' on page \d+ undefined", log)))
    out["overfull_hbox"] = len(re.findall(r"^Overfull \\hbox", log, re.M))
    out["errors"] = [ln for ln in log.splitlines() if ln.startswith("! ")]
    m = re.search(r"Output written on .*?\((\d+) pages?", log)
    out["pages_from_log"] = int(m.group(1)) if m else None
    return out


def pdf_pages(pdf: Path) -> int | None:
    try:
        from pypdf import PdfReader
        return len(PdfReader(str(pdf)).pages)
    except Exception:  # noqa: BLE001 - fall back to the log
        return None


