# Markdown -> LaTeX
# --------------------------------------------------------------------------- #
def preprocess(md: str, notes: dict) -> str:
    # "## 6.1 Title" -> "## Title" (LaTeX numbers the sections).
    md = re.sub(r"^(#{2,6})\s+\d+(\.\d+)*\.?\s+", r"\1 ", md, flags=re.M)
    # [@TODO:...] placeholders -> visible marker instead of a failing \cite.
    md, n = re.subn(r"\[@TODO:[^\]]*\]", r"\\textbf{[citation to verify]}", md)
    notes["todo_citations"] = notes.get("todo_citations", 0) + n
    # Unicode math symbols -> inline math.
    md = re.sub(
        r"×\s?10([⁰¹²³⁴⁵⁶⁷⁸⁹⁻⁺]+)",
        lambda m: raw_math(r"\times 10^{" + m.group(1).translate(SUPERSCRIPTS) + "}"),
        md,
    )
    md = re.sub(
        r"([⁰¹²³⁴⁵⁶⁷⁸⁹⁻⁺]+)",
        lambda m: raw_math("^{" + m.group(1).translate(SUPERSCRIPTS) + "}"),
        md,
    )
    for ch, rep in SYMBOLS.items():
        md = md.replace(ch, raw_math(rep))
    return md


def image_paths(md: str) -> list[str]:
    return re.findall(r"!\[[^\]]*\]\(([^)\s]+)", md)


def pandoc_latex(md: str) -> str:
    cmd = [
        str(PANDOC), "-f", "markdown-auto_identifiers", "-t", "latex",
        "--natbib", "--syntax-highlighting=none", "--wrap=none",
        "--lua-filter", str(FILTER), "-M", f"root_dir={ROOT}",
    ]
    proc = subprocess.run(cmd, input=md, capture_output=True, text=True, cwd=ROOT)
    if proc.returncode != 0:
        raise RuntimeError(f"pandoc failed:\n{proc.stderr}")
    if proc.stderr.strip():
        print(f"  [pandoc] {proc.stderr.strip()}", file=sys.stderr)
    return postprocess(proc.stdout)


def postprocess(tex: str) -> str:
    # natbib citation commands -> IEEEtran's \cite (optional arguments dropped).
    tex = re.sub(r"\\cite(?:p|t|alp|alt|author|year)?\*?(?:\[[^\]]*\]){0,2}\{", r"\\cite{", tex)
    # The `cite` package prefers no spaces inside the key list.
    tex = re.sub(r"\\cite\{([^}]*)\}", lambda m: "\\cite{" + m.group(1).replace(" ", "") + "}", tex)
    # Table group rows (an italic label with empty cells) get a thin rule above them, unless one is already there.
    out = []
    for line in tex.split("\n"):
        if re.match(r"\\emph\{[^}]*\}(\s*&\s*)+\\\\", line.strip()) and out and out[-1].strip() != "\\midrule":
            out.append("\\midrule")
        out.append(line)
    tex = "\n".join(out)
    for name in ("BrowseComp-Plus", "GPT-5.2", "GPT-5", "Pi-Serini", "Qwen3.6-35B-A3B", "Dr-DCI", "OBLIQ-Bench"):
        tex = re.sub(r"(?<![\\w{/.-])" + re.escape(name) + r"(?![\\w}/-])", lambda m: "\\mbox{" + m.group(0) + "}", tex)
    return tex.strip() + "\n"


def tex_escape(s: str) -> str:
    return re.sub(r"([&%$#_{}])", r"\\\1", s)


def sanitize_bib(src: Path, dst: Path) -> int:
    """Copy the bibliography without its `note` fields.

    The notes record how each entry was verified (dates, URLs with underscores)
    and are not meant to be printed; IEEEtran.bst would print them and an
    unescaped underscore in one of them breaks the compile. Returns the number
    of fields removed."""
    text = src.read_text(encoding="utf-8")
    # Also drop `url` fields from entries that carry a DOI: IEEEtran prints the DOI, and the
    # "[Online]. Available: ..." line would repeat it (about a third of a page over 45 entries).
    parts = re.split(r"(?=^@)", text, flags=re.M)
    # (arXiv DOIs 10.48550/... are excluded: IEEEtran does not print them, so the URL is the only identifier)
    text = "".join(_strip_field(p, "url") if re.search(r"^[ \t]*doi[ \t]*=(?![ \t]*[{\"]?[ \t]*10\.48550)", p, re.M | re.I) else p for p in parts)
    # Entries whose only locator is an arXiv URL: print "arXiv:ID" in howpublished (IEEE's compact form) instead of
    # a full "[Online]. Available:" line, which saves a line per entry; entries that already have a howpublished
    # keep it and just lose the URL line. Proceedings/journal entries with an arXiv URL lose the URL (the venue
    # identifies them).
    def _arxiv_compact(entry: str) -> str:
        m = re.search(r"^[ \t]*url[ \t]*=[ \t]*[{\"]https?://arxiv\.org/abs/([^}\"]+)[}\"]", entry, re.M | re.I)
        if not m:
            return entry
        arxiv_id = m.group(1).strip()
        entry = _strip_field(entry, "url")
        if entry.lstrip().lower().startswith("@misc") and not re.search(r"^[ \t]*howpublished[ \t]*=", entry, re.M | re.I):
            entry = re.sub(r"^(@misc\{[^,]+,)", r"\1\n  howpublished = {arXiv:" + arxiv_id + "},", entry, count=1, flags=re.I)
        return entry
    text = "".join(_arxiv_compact(p) for p in re.split(r"(?=^@)", text, flags=re.M))
    # Entries that name a venue (booktitle or journal) need no URL line either: IEEE style prints the venue, and
    # the "[Online]. Available:" line only costs space. URLs stay on @misc entries without a venue (model cards,
    # system cards, repositories).
    def _venue_drop_url(entry: str) -> str:
        if re.search(r"^[ \t]*(booktitle|journal)[ \t]*=", entry, re.M | re.I):
            return _strip_field(entry, "url")
        return entry
    text = "".join(_venue_drop_url(p) for p in re.split(r"(?=^@)", text, flags=re.M))
    return _strip_and_write(text, dst, "note")


def _strip_field(text: str, name: str) -> str:
    class _Sink:
        def write_text(self, s, encoding=None):
            self.s = s
    sink = _Sink(); _strip_and_write(text, sink, name)  # type: ignore[arg-type]
    return sink.s


def _strip_and_write(text: str, dst, name: str) -> int:
    out, i, removed = [], 0, 0
    rx = re.compile(r"^[ \t]*" + name + r"[ \t]*=[ \t]*", re.M | re.I)
    while True:
        m = rx.search(text, i)
        if not m:
            out.append(text[i:])
            break
        out.append(text[i:m.start()])
        j = m.end()
        if j < len(text) and text[j] == "{":
            depth = 0
            while j < len(text):
                if text[j] == "{":
                    depth += 1
                elif text[j] == "}":
                    depth -= 1
                    if depth == 0:
                        j += 1
                        break
                j += 1
        elif j < len(text) and text[j] == '"':
            j = text.index('"', j + 1) + 1
        else:  # bare value up to the next comma or newline
            while j < len(text) and text[j] not in ",\n":
                j += 1
        # drop a trailing comma and the rest of the line
        k = j
        while k < len(text) and text[k] in " \t":
            k += 1
        if k < len(text) and text[k] == ",":
            k += 1
        while k < len(text) and text[k] in " \t":
            k += 1
        if k < len(text) and text[k] == "\n":
            k += 1
        i = k
        removed += 1
    dst.write_text("".join(out), encoding="utf-8")
    return removed


