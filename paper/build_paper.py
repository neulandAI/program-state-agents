# Word count
# --------------------------------------------------------------------------- #
def prose_words(body: str) -> int:
    lines = []
    for line in body.split("\n"):
        s = line.strip()
        if not s or s.startswith("#") or s.startswith("|") or s.startswith("!["):
            continue
        lines.append(line)
    text = "\n".join(lines)
    text = re.sub(r"!\[[^\]]*\]\([^)]*\)(\{[^}]*\})?", " ", text)   # images
    text = re.sub(r"\[@[^\]]*\]", " ", text)                        # [@cite; @cite]
    text = re.sub(r"(?<![\w.])@[\w:+-]+", " ", text)                 # bare @key
    text = re.sub(r"`[^`]*`", " ", text)                             # inline code
    text = re.sub(r"\\[A-Za-z]+(\{[^}]*\})*", " ", text)             # raw LaTeX
    text = re.sub(r"[*_]{1,3}", "", text)                            # emphasis
    text = re.sub(r"\[([^\]]*)\]\([^)]*\)", r"\1", text)             # links
    return len([t for t in text.split() if re.search(r"[A-Za-z0-9]", t)])


def wordcount() -> int:
    rows = []
    total = 0
    for p in [MANUSCRIPT / "01_abstract.md", *chapter_files()]:
        meta, body = split_front_matter(p.read_text(encoding="utf-8"))
        status = str(meta.get("status", ""))
        title, rest = split_h1(body)
        n = prose_words(rest)
        skipped = status in SKIP_STATUS
        rows.append((p.name, title or "", status, n, skipped))
        if not skipped:
            total += n
    width = max(len(r[0]) for r in rows)
    print(f"{'file':<{width}}  {'words':>6}  status        title")
    for name, title, status, n, skipped in rows:
        flag = " (skipped)" if skipped else ""
        print(f"{name:<{width}}  {n:>6}  {status:<12}  {title}{flag}")
    print(f"{'total (included files)':<{width}}  {total:>6}")
    return 0


# --------------------------------------------------------------------------- #
# Build
# --------------------------------------------------------------------------- #
def assemble(findings: list[str], notes: dict) -> tuple[str, list[str], list[str]]:
    meta_title, _ = split_front_matter((MANUSCRIPT / "00_title.md").read_text(encoding="utf-8"))
    title = str(meta_title.get("working_title") or meta_title.get("title") or "Untitled draft")

    abs_meta, abs_body = split_front_matter((MANUSCRIPT / "01_abstract.md").read_text(encoding="utf-8"))
    _, abs_rest = split_h1(abs_body)
    scan_markdown("01_abstract.md", abs_rest, findings)
    abstract_tex = pandoc_latex(preprocess(abs_rest, notes))
    scan_tex("01_abstract.md", abstract_tex, findings)

    included, skipped = [], []
    sections = []
    figures: list[str] = []
    for p in chapter_files():
        meta, body = split_front_matter(p.read_text(encoding="utf-8"))
        status = str(meta.get("status", "")).strip()
        if status in SKIP_STATUS:
            skipped.append(f"{p.name} (status: {status})")
            continue
        title_h1, rest = split_h1(body)
        if title_h1 is None:
            title_h1 = str(meta.get("title", p.stem))
            findings.append(f"{p.name}: no H1 after front matter; used front-matter title")
        scan_markdown(p.name, rest, findings)
        figures += image_paths(rest)
        tex = pandoc_latex(preprocess(rest, notes))
        scan_tex(p.name, tex, findings)
        sections.append(f"% ---- {p.name}\n\\section{{{tex_escape(title_h1)}}}\n{tex}")
        included.append(p.name)

    # Copy existing figure files next to main.tex; missing ones become placeholders.
    fig_dir = BUILD / "figures"
    fig_dir.mkdir(parents=True, exist_ok=True)
    for src in figures:
        s = Path(src) if Path(src).is_absolute() else ROOT / src
        if s.exists():
            shutil.copy2(s, fig_dir / s.name)
        else:
            findings.append(f"figure file missing, placeholder used: {src}")

    doc = [PREAMBLE]
    if ARXIV:   # arXiv preprint: IEEE's required notice for a paper submitted to IEEE, as a first-page footnote
        doc.append("\\IEEEoverridecommandlockouts")
        doc.append(f"\\title{{{tex_escape(title)}\\thanks{{{ARXIV_NOTICE}}}}}")
    else:
        doc.append(f"\\title{{{tex_escape(title)}}}")
    if AUTHORS and AUTHOR_STYLE == "columns":   # IEEE conference template layout: one block per author
        blocks = []
        for n, ids in AUTHORS:
            lines = []
            for a in ids:
                dept, org, place = AFF_PARTS[a]
                lines += ([f"\\textit{{{dept}}}"] if dept else []) + [f"\\textit{{{org}}}", place]
            blocks.append(f"\\IEEEauthorblockN{{{n}}}\n\\IEEEauthorblockA{{" + "\\\\\n".join(lines) + "}")
        # at most four blocks per row (\linebreakand: a row break inside IEEEtran's author table)
        doc.append("\\makeatletter\\newcommand{\\linebreakand}{\\end{@IEEEauthorhalign}\\hfill\\mbox{}\\par"
                   "\\mbox{}\\hfill\\begin{@IEEEauthorhalign}}\\makeatother")
        rows = ["\n\\and\n".join(blocks[i:i + 4]) for i in range(0, len(blocks), 4)]
        doc.append("\\author{" + "\n\\linebreakand\n".join(rows) + "}")
    elif AUTHORS:
        marked = [n + "".join(f"\\IEEEauthorrefmark{{{a}}}" for a in affs) for n, affs in AUTHORS]
        names = ", ".join(marked[:4]) + ",\\\\" + ", ".join(marked[4:])   # two lines: IEEEauthorblockN does not wrap
        affs = "\n".join(f"\\IEEEauthorblockA{{\\IEEEauthorrefmark{{{k}}}{v}}}" for k, v in AFFILIATIONS.items())
        doc.append(f"\\author{{\\IEEEauthorblockN{{{names}}}\n{affs}}}")
    elif AUTHOR_LINE:
        doc.append(f"\\author{{\\IEEEauthorblockN{{{AUTHOR_LINE}}}}}")
    else:
        doc.append("\\author{}")
    doc.append("\\begin{document}\n\\maketitle")
    if PAGE_NUMBERS:   # review copy: page numbers in the footer (IEEEtran conference mode omits them; IEEE adds its own at publication)
        doc.append("\\thispagestyle{plain}\\pagestyle{plain}")
    doc.append("\\begin{abstract}\n" + abstract_tex + "\\end{abstract}")
    doc.append("\\begin{IEEEkeywords}\n" + ", ".join(KEYWORDS)[:1].upper() + ", ".join(KEYWORDS)[1:] + "\n\\end{IEEEkeywords}")
    doc.append("\\IEEEpeerreviewmaketitle")
    doc.extend(sections)
    doc.append("\\bibliographystyle{IEEEtran}\n\\bibliography{references}")
    doc.append("\\end{document}")
    return "\n\n".join(doc) + "\n", included, skipped


def compile_tex(verbose: bool) -> tuple[int, str]:
    cmd = [str(TECTONIC), "--keep-logs", "--keep-intermediates", "--chatter", "minimal", "main.tex"]
    proc = subprocess.run(cmd, cwd=BUILD, capture_output=True, text=True)
    out = proc.stdout + proc.stderr
    if verbose and out.strip():
        print(out)
    return proc.returncode, out


def build(args) -> int:
    for tool in (PANDOC, TECTONIC):
        if not tool.exists():
            print(f"missing tool: {tool} (.tools/bin/pandoc and .tools/bin/tectonic)", file=sys.stderr)
            return 2
    BUILD.mkdir(parents=True, exist_ok=True)
    findings: list[str] = []
    notes: dict = {}

    t0 = time.time()
    tex, included, skipped = assemble(findings, notes)
    (BUILD / "main.tex").write_text(tex, encoding="utf-8")
    removed_notes = sanitize_bib(BIB, BUILD / "references.bib")
    t_pandoc = time.time() - t0

    print(f"chapters included: {', '.join(included)}")
    if skipped:
        print(f"chapters skipped:  {', '.join(skipped)}")
    print(f"wrote {BUILD / 'main.tex'} ({t_pandoc:.1f} s); references.bib copied with {removed_notes} note fields removed")
    if notes.get("todo_citations"):
        print(f"[@TODO:...] placeholders replaced: {notes['todo_citations']}")

    rc = 0
    if not args.tex_only:
        t1 = time.time()
        rc, out = compile_tex(args.verbose)
        t_tex = time.time() - t1
        log = (BUILD / "main.log").read_text(encoding="utf-8", errors="replace") if (BUILD / "main.log").exists() else ""
        blg = (BUILD / "main.blg").read_text(encoding="utf-8", errors="replace") if (BUILD / "main.blg").exists() else ""
        info = parse_log(log, blg)
        pdf = BUILD / "main.pdf"
        if rc != 0:
            print(f"tectonic FAILED (exit {rc}) after {t_tex:.1f} s (citation list below is from an incomplete run)")
            for ln in info["errors"][:20]:
                print("  " + ln)
            tail = [ln for ln in out.splitlines() if ln.strip()][-15:]
            for ln in tail:
                print("  " + ln)
        else:
            pages = pdf_pages(pdf) if pdf.exists() else None
            if pages is None:
                pages = info["pages_from_log"]
            print(f"compiled {pdf} in {t_tex:.1f} s")
            print(f"pages: {pages}")
        und = info["undefined_citations"]
        print(f"undefined citations: {len(und)}" + (f" -> {', '.join(und)}" if und else ""))
        if info["undefined_refs"]:
            print(f"undefined \\ref labels: {', '.join(info['undefined_refs'])}")
        if info["overfull_hbox"]:
            print(f"overfull hboxes: {info['overfull_hbox']}")

    if findings:
        print("conversion notes:")
        for f in findings:
            print("  - " + f)
    else:
        print("conversion notes: none")
    print(f"total time: {time.time() - t0:.1f} s")
    return rc


